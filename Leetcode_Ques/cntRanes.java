class Solution {

    public long countCommas(long n) {

        if (n < 1000)
            return 0;

        long ans = 0;

        if (n <= 999999) {

            ans = n - 1000 + 1;

        } else if (n <= 999999999) {

            ans = 999999 - 1000 + 1;
            ans += (n - 1000000 + 1) * 2;

        } else if (n <= 999999999999L) {

            ans = 999999 - 1000 + 1;
            ans += (999999999L - 1000000 + 1) * 2;
            ans += (n - 1000000000L + 1) * 3;

        } else if (n <= 999999999999999L) {

            ans = 999999 - 1000 + 1;
            ans += (999999999L - 1000000 + 1) * 2;
            ans += (999999999999L - 1000000000L + 1) * 3;
            ans += (n - 1000000000000L + 1) * 4;

        } else {

            ans = 999999 - 1000 + 1;
            ans += (999999999L - 1000000 + 1) * 2;
            ans += (999999999999L - 1000000000L + 1) * 3;
            ans += (999999999999999L - 1000000000000L + 1) * 4;
            ans += (n - 1000000000000000L + 1) * 5;
        }

        return ans;
    }
}